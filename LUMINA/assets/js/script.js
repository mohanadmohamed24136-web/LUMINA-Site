function showTab(tabId) {
    if (tabId === 'premium' && (!currentUser || currentUser.role !== 'designer')) {
        showToast(currentLang === 'ar' ? 'هذا الخيار متاح للمصممين فقط' : 'This option is only available for designers', 'error');
        return;
    }
    document.querySelectorAll('[id^="tab-"]').forEach(tab => tab.classList.add('hidden'));
    const target = document.getElementById(`tab-${tabId}`);
    if (target) target.classList.remove('hidden');

    // Update active state in sidebar
    document.querySelectorAll('aside nav button').forEach(btn => {
        btn.classList.remove('bg-white/5', 'text-primary-cyan', 'border-primary-cyan/20');
        btn.classList.add('text-gray-500');
    });
    
    const clickedBtn = Array.from(document.querySelectorAll('aside nav button')).find(btn => {
        const onclick = btn.getAttribute('onclick');
        return onclick && onclick.includes(`'${tabId}'`);
    });
    
    if (clickedBtn) {
        clickedBtn.classList.add('bg-white/5', 'text-primary-cyan', 'border-primary-cyan/20');
        clickedBtn.classList.remove('text-gray-500');
    }

    if (tabId === 'favorites') {
        renderDashboardFavorites();
    }
    
    if (tabId === 'orders') {
        renderOrdersInDashboard();
    }

    if (tabId === 'my-products') {
        renderDesignerProducts();
    }
    
    if (tabId === 'premium') {
        renderPremiumStatus();
    }
    
    if (tabId === 'analytics') {
        initAnalytics();
    }

    if (tabId === 'finance') {
        initFinance();
    }
}

