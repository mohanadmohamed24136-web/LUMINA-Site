async function placeOrder() {
    if (!currentUser) {
        showToast(currentLang === 'ar' ? 'يرجى تسجيل الدخول أولاً' : 'Please Sign In First', 'error');
        return;
    }

    const btn = document.getElementById('place-order-btn');
    if (btn && btn.disabled) return;

    const name = document.getElementById('checkout-name').value;
    const email = document.getElementById('checkout-email').value;
    const phone = document.getElementById('checkout-phone').value;
    const address = document.getElementById('checkout-address').value;

    if (!name || !email || !phone || !address) {
        showToast(currentLang === 'ar' ? 'يرجى ملء جميع الحقول' : 'Please fill all shipping details', 'error');
        return;
    }

    if (btn) {
        btn.disabled = true;
        btn.innerHTML = `
            <div class="flex items-center gap-3">
                <div class="w-4 h-4 border-2 border-black border-t-transparent rounded-full animate-spin"></div>
                <span>Manifesting Order...</span>
            </div>
        `;
    }

    const subtotal = currentCart.reduce((sum, item) => sum + (parseFloat(item.price) * (item.quantity || 1)), 0);
    const total = subtotal + 50 + (subtotal * 0.1);

    const orderPayload = {
        order_id: 'LUM-' + Math.random().toString(36).substr(2, 6).toUpperCase(),
        user_email: currentUser.email,
        total_amount: total,
        shipping: { name, email, phone, address },
        payment_method: 'Direct Protocol (Simulated)',
        items: currentCart.map(item => ({
            id: item.product_id,
            name: item.name,
            price: item.price,
            quantity: item.quantity || 1,
            selected_size: item.selected_size,
            architect: item.architect
        }))
    };

    try {
        const response = await fetch(`${API_BASE}/orders`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(orderPayload)
        });

        if (response.ok) {
            await clearCart();
            closeCheckout();
            showToast(currentLang === 'ar' ? 'تم تأكيد الطلب بنجاح!' : 'Order Manifested Successfully!', 'success');
            setTimeout(() => {
                window.location.href = 'customer-dashboard.html';
            }, 2000);
        } else {
            throw new Error('Order failed');
        }
    } catch (err) {
        console.error('Checkout Error:', err);
        showToast(currentLang === 'ar' ? 'فشل إرسال الطلب' : 'Order Protocol Failed', 'error');
        if (btn) {
            btn.disabled = false;
            btn.innerHTML = `<i data-lucide="check-circle" class="w-5 h-5"></i> Place Order`;
            if (window.lucide) lucide.createIcons();
        }
    }
}

