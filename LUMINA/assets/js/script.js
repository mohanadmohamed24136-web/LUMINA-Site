function getCart() {
    return currentCart || [];
}

function updateCartBadge() {
    const cart = getCart();
    const count = cart.reduce((sum, item) => sum + (item.quantity || 1), 0);
    const badge = document.getElementById('cart-badge');
    if (badge) {
        badge.textContent = count;
        if (count > 0) {
            badge.classList.remove('hidden');
        } else {
            badge.classList.add('hidden');
        }
    }
}

async function addToCart(id, name, price, img, architect, quantity = 1, size = null, color = null) {
    if (!currentUser) {
        showToast(currentLang === 'ar' ? 'يجب أن تكون مسجلاً أولاً للقيام بهذا الإجراء' : 'You must be registered first for this action', 'error');
        window.location.href = 'login.html';
        return;
    }

    try {
        const response = await fetch(`${API_BASE}/cart`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                user_email: currentUser.email,
                product_id: id,
                name,
                price,
                img,
                architect,
                quantity: quantity || 1,
                selected_size: size,
                selected_color: color
            })
        });

        if (response.ok) {
            currentCart = await response.json();
            updateCartBadge();
            showToast(currentLang === 'ar' ? 'تمت إضافة المنتج للعربة' : 'Product added to cart');
        }
    } catch (err) {
        console.error('Add to Cart Error:', err);
    }
}

async function removeFromCart(productId) {
    if (!currentUser) return;
    try {
        const response = await fetch(`${API_BASE}/cart/${currentUser.email}/${productId}`, {
            method: 'DELETE'
        });
        if (response.ok) {
            currentCart = await response.json();
            updateCartBadge();
            updateCartUI();
        }
    } catch (err) {
        console.error('Remove from Cart Error:', err);
    }
}

