function handleMultipleImages(input) {
    const container = document.getElementById('image-preview-container');
    const status = document.getElementById('upload-status');
    if (!container || !status) return;

    container.innerHTML = '';
    const files = Array.from(input.files).slice(0, 5); // Limit to 5
    
    if (files.length > 0) {
        status.textContent = `${files.length} images selected`;
        files.forEach((file, index) => {
            const reader = new FileReader();
            reader.onload = (e) => {
                const div = document.createElement('div');
                div.className = 'aspect-square rounded-xl overflow-hidden border border-white/10 relative group';
                div.innerHTML = `
                    <img src="${e.target.result}" class="w-full h-full object-cover">
                    <div class="absolute inset-0 bg-black/40 opacity-0 group-hover:opacity-100 transition-opacity flex items-center justify-center">
                        <span class="text-[8px] font-black text-white uppercase">${index === 0 ? 'Primary' : ''}</span>
                    </div>
                `;
                container.appendChild(div);
            };
            reader.readAsDataURL(file);
        });
    } else {
        status.textContent = 'Select up to 5 images';
    }
}

async function initializeAsset() {
    // Ensure app is initialized
    if (!currentUser) {
        const userId = getCookie('userId');
        if (userId) {
            try {
                const response = await fetch(`${API_BASE}/auth/profile?id=${userId}`);
                if (response.ok) {
                    currentUser = await response.json();
                }
            } catch (err) {
                console.error('Wait for user error:', err);
            }
        }
    }

    const user = currentUser;
    if (!user) {
        showToast(currentLang === 'ar' ? 'يجب تسجيل الدخول أولاً' : 'Please login first', 'error');
        return;
    }

    // Strict profile validation before upload
    const missingProfileFields = [];
    if (!user.phone || user.phone.trim() === "") missingProfileFields.push(currentLang === 'ar' ? 'رقم الهاتف' : 'Phone Number');
    if (!user.address || user.address.trim() === "") missingProfileFields.push(currentLang === 'ar' ? 'العنوان' : 'Address');
    if (!user.bio || user.bio.trim() === "") missingProfileFields.push(currentLang === 'ar' ? 'السيرة الذاتية' : 'Bio');
    if (!user.photo) missingProfileFields.push(currentLang === 'ar' ? 'صورة البروفايل' : 'Profile Photo');

    if (missingProfileFields.length > 0) {
        const msg = currentLang === 'ar' 
            ? `يجب إكمال ملفك الشخصي قبل الرفع. الخانات الناقصة: ${missingProfileFields.join('، ')}` 
            : `Please complete your profile before uploading. Missing: ${missingProfileFields.join(', ')}`;
        showToast(msg, 'error');
        if (user.role === 'designer') window.location.href = 'designer-portal.html?tab=profile';
        return;
    }

    const nameInput = document.getElementById('prod-name');
    const priceInput = document.getElementById('prod-price');
    const imageInput = document.getElementById('prod-image');
    const descInput = document.getElementById('prod-description');
    
    const name = nameInput?.value.trim();
    const price = priceInput?.value.trim();
    const imageFiles = imageInput?.files;
    const description = descInput?.value.trim();

    // Check sizes
    const sizes = {
        s: document.getElementById('size-s')?.value.trim(),
        m: document.getElementById('size-m')?.value.trim(),
        l: document.getElementById('size-l')?.value.trim(),
        xl: document.getElementById('size-xl')?.value.trim(),
        xxl: document.getElementById('size-xxl')?.value.trim()
    };

    // Strict Product Validation
    const errors = [];
    if (!name) errors.push(currentLang === 'ar' ? 'اسم المنتج' : 'Product Name');
    if (!price || isNaN(price) || parseFloat(price) <= 0) errors.push(currentLang === 'ar' ? 'سعر صحيح' : 'Valid Price');
    if (!imageFiles || imageFiles.length === 0) errors.push(currentLang === 'ar' ? 'صورة واحدة على الأقل' : 'At least one image');
    if (!description || description.length < 20) errors.push(currentLang === 'ar' ? 'وصف مفصل (20 حرف على الأقل)' : 'Detailed Description (min 20 chars)');
    
    // Check if at least one size has "Available" or a value
    const hasSize = Object.values(sizes).some(v => v && v.toLowerCase() !== '-' && v.toLowerCase() !== 'n/a');
    if (!hasSize) errors.push(currentLang === 'ar' ? 'تحديد مقاس واحد متاح على الأقل' : 'At least one available size');

    if (errors.length > 0) {
        showToast(currentLang === 'ar' ? `البيانات ناقصة: ${errors.join('، ')}` : `Missing data: ${errors.join(', ')}`, 'error');
        return;
    }

    const formData = new FormData();
    formData.append('name', name);
    formData.append('price', price);
    formData.append('location', user.address);
    formData.append('architect', (user.username || user.name));
    formData.append('email', user.email);
    formData.append('phone', user.phone);
    
    Array.from(imageFiles).slice(0, 5).forEach(file => formData.append('images', file));

    formData.append('size_s', sizes.s || '-');
    formData.append('size_m', sizes.m || '-');
    formData.append('size_l', sizes.l || '-');
    formData.append('size_xl', sizes.xl || '-');
    formData.append('size_xxl', sizes.xxl || '-');
    formData.append('quantity', document.getElementById('prod-quantity')?.value || '1');
    formData.append('colors', document.getElementById('prod-colors')?.value || '');
    formData.append('description', description);

    const submitBtn = document.getElementById('initialize-asset-btn');
    const originalBtnContent = submitBtn ? submitBtn.innerHTML : '';
    
    if (submitBtn) {
        submitBtn.disabled = true;
        submitBtn.innerHTML = `
            <div class="flex items-center gap-3">
                <div class="w-4 h-4 border-2 border-black border-t-transparent rounded-full animate-spin"></div>
                <span>Uploading Masterpiece...</span>
            </div>
        `;
    }

    try {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 30000); // 30 second timeout

        const response = await fetch(`${API_BASE}/products`, {
            method: 'POST',
            body: formData,
            signal: controller.signal
        });
        clearTimeout(timeoutId);

        const contentType = response.headers.get("content-type");
        let data;
        if (contentType && contentType.indexOf("application/json") !== -1) {
            data = await response.json();
        }

        if (response.ok) {
            currentUser = { ...user, ...data.user };
            showToast(currentLang === 'ar' ? 'تم نشر التصميم بنجاح!' : 'Asset Initialized Successfully!');
            setTimeout(() => location.reload(), 1500);
        } else {
            // Try to get detailed error from response
            let errorMsg = currentLang === 'ar' ? 'حدث خطأ أثناء الرفع' : 'Upload failed';
            if (data && data.error) {
                errorMsg = data.error;
            }
            
            showToast('Error: ' + errorMsg, 'error');
            console.error('Upload Failed:', data);
            
            if (submitBtn) {
                submitBtn.disabled = false;
                submitBtn.innerHTML = originalBtnContent;
            }
        }
    } catch (err) {
        console.error('Upload Error:', err);
        showToast(currentLang === 'ar' ? 'خطأ في الاتصال، يرجى المحاولة لاحقاً' : 'Connection Error, please try again later', 'error');
        if (submitBtn) {
            submitBtn.disabled = false;
            submitBtn.innerHTML = originalBtnContent;
        }
    }
}

