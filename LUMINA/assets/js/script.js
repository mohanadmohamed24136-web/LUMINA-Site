// Initialize App
async function initApp() {
    // Try to load user from cookie
    const userId = getCookie('userId');
    if (userId) {
        try {
            const response = await fetch(`${API_BASE}/auth/profile?id=${userId}`);
            if (response.ok) {
                currentUser = await response.json();
                // Ensure helper cookies are present
                if (!getCookie('userEmail')) setCookie('userEmail', currentUser.email, 7);
                if (!getCookie('userRole')) setCookie('userRole', currentUser.role, 7);
                
                // Load cart and favorites from DB
                await Promise.all([
                    fetchCart(),
                    fetchFavorites()
                ]);
            } else {
                eraseCookie('userId');
            }
        } catch (err) {
            console.error('Init Auth Error:', err);
        }
    }
    updateUI();
    
    // Check for Stripe session status
    const urlParams = new URLSearchParams(window.location.search);
    const status = urlParams.get('status');
    const sessionId = urlParams.get('session_id');

    if (status === 'success') {
        if (sessionId) {
            showToast(currentLang === 'ar' ? 'تمت عملية الشراء وتأكيد الطلب بنجاح!' : 'Order Manifested & Secured Successfully!', 'success');
        } else {
            showToast(currentLang === 'ar' ? 'تهانينا! تم تفعيل الاشتراك البريميوم بنجاح' : 'Premium Protocol Activated Successfully!', 'success');
        }
        // Clean URL
        window.history.replaceState({}, document.title, window.location.pathname);
    } else if (status === 'cancel') {
        showToast(currentLang === 'ar' ? 'تم إلغاء عملية الاشتراك' : 'Subscription Protocol Aborted', 'error');
        window.history.replaceState({}, document.title, window.location.pathname);
    }
    
    // Page specific initializations
    if (document.getElementById('designer-products-grid')) {
        renderHomeProducts();
        renderAIProducts();
        renderDesignerSpotlight();
    }
    if (document.getElementById('cart-items-container')) updateCartUI();
    if (window.location.pathname.includes('admin-portal.html')) {
        showAdminTab('overview');
    }

    // Scroll Reveal
    initReveal();

    // Ensure all icons are rendered
    if (window.lucide) lucide.createIcons();
}

async function renderDesignerSpotlight() {
    const grid = document.getElementById('designer-spotlight-grid');
    if (!grid) return;

    try {
        const response = await fetch(`${API_BASE}/designers`);
        if (!response.ok) throw new Error(`HTTP error! status: ${response.status}`);
        
        const designers = await response.json();

        if (designers.length === 0) {
            // Try fallback if no designers returned from primary endpoint
            return renderDesignerSpotlightFallback(grid);
        }

        renderDesignerSpotlightGrid(grid, designers);
        
    } catch (err) {
        console.error('Designer Spotlight Error:', err);
        renderDesignerSpotlightFallback(grid);
    }
}

async function renderDesignerSpotlightFallback(grid) {
    try {
        const [productsRes, designersRes] = await Promise.all([
            fetch(`${API_BASE}/products`),
            fetch(`${API_BASE}/designers`).catch(() => null)
        ]);

        const products = await productsRes.json();
        let designersData = [];
        if (designersRes && designersRes.ok) {
            designersData = await designersRes.json();
        }

        if (!products || products.length === 0) {
            grid.innerHTML = '<p class="col-span-full text-center text-gray-500 text-[10px] font-black uppercase tracking-widest py-20">No active architects manifested yet.</p>';
            return;
        }

        // Extract unique designers from products
        const designerMap = new Map();
        products.forEach(p => {
            if (p.architect && !designerMap.has(p.architect)) {
                // Try to find designer info in designersData
                const info = designersData.find(d => d.username === p.architect || d.name === p.architect);
                
                designerMap.set(p.architect, {
                    username: p.architect,
                    asset_count: products.filter(pr => pr.architect === p.architect).length,
                    bio: info ? info.bio : 'Neural Architect',
                    email: info ? info.email : (p.designerEmail || ''),
                    photo: info ? info.photo : null,
                    rating: info ? info.rating : '5.0'
                });
            }
        });

        const designers = Array.from(designerMap.values()).slice(0, 4);
        renderDesignerSpotlightGrid(grid, designers);
    } catch (e) {
        console.error('Fallback Error:', e);
        grid.innerHTML = '<p class="col-span-full text-center text-red-500 text-[10px] font-black uppercase tracking-widest py-20">Protocol Failure: Data Link Interrupted</p>';
    }
}

