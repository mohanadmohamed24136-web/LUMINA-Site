// Logic to handle clicking on designer card from home page
async function openDesignerProfileFromHome(email, username) {
    // Redirect to a product page for this designer, but with a flag to open their profile
    // Or we could implement a global designer modal, but for now, we'll try to find one of their products
    try {
        const res = await fetch(`${API_BASE}/products`);
        const products = await res.json();
        const firstProduct = products.find(p => p.designerEmail === email || p.architect === username);
        
        if (firstProduct) {
            window.location.href = `product-detail.html?id=${firstProduct.id}&openProfile=true`;
        } else {
            showToast(currentLang === 'ar' ? 'المصمم ليس لديه منتجات حالياً' : 'Designer has no active assets', 'info');
        }
    } catch (e) {
        console.error('Home Profile Open Error:', e);
    }
}

// --- Scroll Reveal Logic ---
function initReveal() {
    const reveals = document.querySelectorAll('.reveal');
    if (reveals.length === 0) return;
    
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('active');
            }
        });
    }, observerOptions);

    reveals.forEach(el => observer.observe(el));
}

