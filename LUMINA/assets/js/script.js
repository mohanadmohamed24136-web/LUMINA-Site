async function triggerPhotoUpload() {
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = 'image/*';
    input.onchange = async (e) => {
        const file = e.target.files[0];
        if (file) {
            const user = currentUser;
            if (!user) return;

            const formData = new FormData();
            formData.append('id', user.id);
            formData.append('photo', file); // This matches backend's upload.single('photo')
            formData.append('username', user.username || user.name);
            formData.append('email', user.email);

            try {
                const response = await fetch(`${API_BASE}/auth/profile`, {
                    method: 'PATCH',
                    body: formData
                });
                if (response.ok) {
                    currentUser = await response.json();
                    location.reload();
                }
            } catch (err) {
                console.error('Photo Upload Error:', err);
            }
        }
    };
    input.click();
}

async function commitChanges() {
    const user = currentUser;
    if (!user) return;

    const name = document.getElementById('input-name').value.trim();
    const phone = document.getElementById('input-phone').value.trim();
    const address = document.getElementById('input-address').value.trim();
    const bio = document.getElementById('input-bio').value.trim();
    const photoInput = document.getElementById('upload-photo-input');
    const photoFile = photoInput?.files[0];

    // Mandatory fields check
    if (!name || !phone || !address || !bio) {
        showToast(currentLang === 'ar' ? 'يرجى ملء جميع الحقول الإلزامية' : 'Please fill all mandatory fields', 'error');
        return;
    }

    const formData = new FormData();
    formData.append('id', user.id);
    formData.append('username', name);
    formData.append('phone', phone);
    formData.append('address', address);
    formData.append('bio', bio);
    if (photoFile) {
        formData.append('photo', photoFile);
    }

    try {
        const response = await fetch(`${API_BASE}/auth/profile/update`, {
            method: 'POST',
            body: formData
        });

        if (response.ok) {
            const data = await response.json();
            currentUser = data.user;
            showToast(currentLang === 'ar' ? 'تم تحديث البيانات بنجاح' : 'Identity Updated Successfully');
            setTimeout(() => location.reload(), 1500);
        } else {
            const errorData = await response.json();
            const errorMsg = errorData.error || (currentLang === 'ar' ? 'فشل تحديث البيانات' : 'Failed to update protocol');
            showToast(errorMsg, 'error');
        }
    } catch (err) {
        console.error('Update Error:', err);
        showToast(currentLang === 'ar' ? 'حدث خطأ في النظام' : 'System Error', 'error');
    }
}

