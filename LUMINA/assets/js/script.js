let salesChart = null;
let distributionChart = null;
let activityChart = null;

async function initAnalytics() {
    if (!currentUser) return;

    // Fetch products and orders
    const [products, ordersResponse] = await Promise.all([
        fetchProducts(),
        fetch(`${API_BASE}/orders/${currentUser.email}`)
    ]);
    
    const myProducts = products.filter(p => p.designerEmail === currentUser.email);
    const myOrders = await ordersResponse.json();
    
    // Filter orders to only include items from this designer
    const mySalesItems = [];
    myOrders.forEach(order => {
        if (order.items && Array.isArray(order.items)) {
            order.items.forEach(item => {
                // Check if this item belongs to the current designer
                if (item.designerEmail === currentUser.email || item.architect === currentUser.username || item.architect === currentUser.name) {
                    mySalesItems.push({
                        ...item,
                        date: order.created_at || order.date
                    });
                }
            });
        }
    });

    // Calculate Stats
    const totalRevenue = mySalesItems.reduce((sum, item) => sum + (parseFloat(item.price) * (item.quantity || 1)), 0);
    const totalSold = mySalesItems.reduce((sum, item) => sum + (item.quantity || 1), 0);
    const successRate = myProducts.length > 0 ? (myProducts.filter(p => p.isSold).length / myProducts.length * 100).toFixed(1) : 0;

    document.getElementById('stat-revenue').textContent = `$${totalRevenue.toLocaleString()}`;
    document.getElementById('stat-sold').textContent = totalSold;
    document.getElementById('stat-rate').textContent = `${successRate}%`;

    renderSalesChart(mySalesItems);
    renderDistributionChart(myProducts);
    renderActivityChart(myProducts);
}

function renderSalesChart(salesItems) {
    const ctx = document.getElementById('salesChart')?.getContext('2d');
    if (!ctx) return;

    if (salesChart) salesChart.destroy();

    // Group sales by date
    const salesByDate = {};
    salesItems.forEach(item => {
        const date = new Date(item.date || item.created_at).toLocaleDateString();
        salesByDate[date] = (salesByDate[date] || 0) + (parseFloat(item.price) * (item.quantity || 1));
    });

    const labels = Object.keys(salesByDate).sort((a, b) => new Date(a) - new Date(b));
    const data = labels.map(l => salesByDate[l]);

    salesChart = new Chart(ctx, {
        type: 'line',
        data: {
            labels: labels.length > 0 ? labels : ['No Data'],
            datasets: [{
                label: 'Revenue ($)',
                data: data.length > 0 ? data : [0],
                borderColor: '#00F0FF',
                backgroundColor: 'rgba(0, 240, 255, 0.1)',
                borderWidth: 3,
                fill: true,
                tension: 0.4,
                pointBackgroundColor: '#00F0FF',
                pointBorderColor: '#fff',
                pointHoverRadius: 6
            }]
        },
        options: {
            responsive: true,
            maintainAspectRatio: false,
            plugins: {
                legend: { display: false }
            },
            scales: {
                y: {
                    grid: { color: 'rgba(255, 255, 255, 0.05)' },
                    ticks: { color: '#666', font: { weight: 'bold' } }
                },
                x: {
                    grid: { display: false },
                    ticks: { color: '#666', font: { weight: 'bold' } }
                }
            }
        }
    });
}

function renderDistributionChart(products) {
    const ctx = document.getElementById('distributionChart')?.getContext('2d');
    if (!ctx) return;

    if (distributionChart) distributionChart.destroy();

    const sold = products.filter(p => p.isSold || p.is_sold).length;
    const available = products.length - sold;

    distributionChart = new Chart(ctx, {
        type: 'doughnut',
        data: {
            labels: ['Sold', 'Available'],
            datasets: [{
                data: [sold || 1, available || 1], // Demo data if empty
                backgroundColor: ['#FF00AA', '#00F0FF'],
                borderWidth: 0,
                hoverOffset: 10
            }]
        },
        options: {
            responsive: true,
            maintainAspectRatio: false,
            plugins: {
                legend: {
                    position: 'bottom',
                    labels: { color: '#fff', padding: 20, font: { weight: 'bold', size: 10 } }
                }
            },
            cutout: '70%'
        }
    });
}

function renderActivityChart(products) {
    const ctx = document.getElementById('activityChart')?.getContext('2d');
    if (!ctx) return;

    if (activityChart) activityChart.destroy();

    // Group uploads by month
    const activity = {};
    products.forEach(p => {
        const date = new Date(p.date);
        const month = date.toLocaleString('default', { month: 'short' });
        activity[month] = (activity[month] || 0) + 1;
    });

    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    const data = months.map(m => activity[m] || 0);

    activityChart = new Chart(ctx, {
        type: 'bar',
        data: {
            labels: months,
            datasets: [{
                label: 'Uploads',
                data: data,
                backgroundColor: 'rgba(255, 215, 0, 0.3)',
                borderColor: '#FFD700',
                borderWidth: 2,
                borderRadius: 8
            }]
        },
        options: {
            responsive: true,
            maintainAspectRatio: false,
            plugins: {
                legend: { display: false }
            },
            scales: {
                y: {
                    grid: { color: 'rgba(255, 255, 255, 0.05)' },
                    ticks: { color: '#666', stepSize: 1 }
                },
                x: {
                    grid: { display: false },
                    ticks: { color: '#666' }
                }
            }
        }
    });
}

