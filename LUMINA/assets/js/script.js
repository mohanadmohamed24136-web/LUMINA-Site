function showToast(message, type = 'success') {
    let toastContainer = document.getElementById('toast-container');
    if (!toastContainer) {
        toastContainer = document.createElement('div');
        toastContainer.id = 'toast-container';
        toastContainer.className = 'fixed bottom-8 left-1/2 -translate-x-1/2 z-[500] flex flex-col gap-3 items-center pointer-events-none';
        document.body.appendChild(toastContainer);
    }

    const toast = document.createElement('div');
    toast.className = `glass px-8 py-4 rounded-[2rem] border ${type === 'error' ? 'border-red-500/40' : 'border-primary-cyan/40'} flex items-center gap-4 animate-slide-up shadow-[0_20px_50px_rgba(0,0,0,0.5)] backdrop-blur-2xl pointer-events-auto group/toast`;
    
    const icon = type === 'error' ? 'alert-circle' : 'check-circle';
    const iconColor = type === 'error' ? 'text-red-500' : 'text-primary-cyan';

    toast.innerHTML = `
        <div class="w-10 h-10 rounded-xl bg-white/5 flex items-center justify-center group-hover/toast:scale-110 transition-transform">
            <i data-lucide="${icon}" class="w-5 h-5 ${iconColor}"></i>
        </div>
        <div class="flex flex-col">
            <span class="text-[8px] font-black uppercase tracking-[0.3em] text-gray-500">${type === 'error' ? 'Protocol Error' : 'System Message'}</span>
            <span class="text-[10px] font-black uppercase tracking-widest text-white">${message}</span>
        </div>
    `;

    toastContainer.appendChild(toast);
    if (window.lucide) lucide.createIcons();

    setTimeout(() => {
        toast.style.transform = 'translateY(20px) scale(0.95)';
        toast.style.opacity = '0';
        setTimeout(() => toast.remove(), 600);
    }, 4000);
}

